const DICTIONNAIRES: Record<LangueClient, Dictionnaire> = {
  fr,
  en,
  wo,
  es,
  it,
  de,
  pt,
  ar,
};
const SEPARATEUR_PLURIEL = "||";

export function traducteurClient(langue: LangueClient) {
  const dictionnaire = DICTIONNAIRES[langue];
  const pluriel = new Intl.PluralRules(FICHES_LANGUES[langue].locale);
  return (cle: CleTexteClient, variables?: Record<string, string | number>) => {
    let texte = dictionnaire[cle];
    if (texte.includes(SEPARATEUR_PLURIEL)) {
      const [une, plusieurs] = texte.split(SEPARATEUR_PLURIEL);
      const n = Number(variables?.n);
      texte =
        Number.isFinite(n) && pluriel.select(n) === "one" ? une : plusieurs;
    }
    return texte.replace(/\{(\w+)\}/g, (_, nom: string) =>
      String(variables?.[nom] ?? ""),
    );
  };
}

export type TraduireClient = ReturnType<typeof traducteurClient>;
